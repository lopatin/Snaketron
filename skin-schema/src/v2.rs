/// Convert a v1 document to the v2 form.
///
/// This is the conversion the Builder applies when opening a v1 skin, so it
/// has one obligation above all: **a still v1 document must convert to a
/// stack that compiles to byte-identical ops** — the same guarantee the
/// compositor flip was held to, proven by the same classic trace. Animated
/// documents convert to the expression forms of their tracks and wave, which
/// are visually equivalent by construction (`shift_lightness` baked per step
/// either way) rather than byte-pinned.
pub fn upgrade(doc: &SkinDoc) -> SkinDocV2 {
    use std::fmt::Write as _;

    // Sum a target's tracks into one per-step expression, or None when the
    // target is unmodulated. `track_offset` is `amplitude * sin(tau * (step /
    // STEPS + phase))`; `time` is exactly `step / STEPS` in the bake, so the
    // conversion is the same arithmetic with the clock left symbolic.
    let track_sum = |target: crate::TrackTarget| -> Option<String> {
        let animation = doc.animation.as_ref()?;
        let mut sum = String::new();
        for track in animation.tracks.iter().filter(|t| t.target == target) {
            if !sum.is_empty() {
                sum.push_str(" + ");
            }
            if track.phase == 0.0 {
                write!(sum, "{} * sin(tau * time)", track.amplitude).expect("string write");
            } else {
                write!(
                    sum,
                    "{} * sin(tau * (time + {}))",
                    track.amplitude, track.phase
                )
                .expect("string write");
            }
        }
        (!sum.is_empty()).then_some(sum)
    };

    let fill_ref = || ColorRef {
        target: ColorTarget::Slot {
            slot: SlotName::Fill,
        },
        lighten: track_sum(crate::TrackTarget::BodyLightness).map(PropExpr),
    };

    // The head glow's whole curve, which v1 split across three places: a peak
    // (`max_opacity` plus its tracks), a linear falloff the renderer applied,
    // and a wave added *after* that falloff. Writing it out is not a
    // translation loss — it is the point. The falloff stops being a shape the
    // renderer knows and becomes something an author can see and change.
    //
    // The structure below mirrors the legacy arithmetic exactly, term for
    // term and in the same association order, which is what lets a still
    // document keep painting byte-identical pixels.
    let ramp_opacity = {
        let peak = match track_sum(crate::TrackTarget::GradientOpacity) {
            // Clamped the way the baked frame clamped it, so a peak driven
            // past 1 by its tracks behaves as it always did.
            Some(tracks) => format!("clamp({} + {tracks}, 0, 1)", doc.head.gradient.max_opacity),
            None => format!("{}", doc.head.gradient.max_opacity),
        };
        let mut source = format!("(1 - s / {}) * {peak}", doc.head.gradient.length_cells);
        if let Some(wave) = doc.animation.as_ref().and_then(|spec| spec.wave.as_ref()) {
            // The wave rides on top of the falloff rather than under it, which
            // is why light still reaches the tail end of the glow.
            write!(
                source,
                " + {} * sin(tau * (s / {} - {} * time))",
                wave.amplitude, wave.cells_per_crest, wave.crests_per_cycle
            )
            .expect("string write");
        }
        PropExpr(source)
    };

    let layer = |name: &str, body: LayerBodyV2| LayerV2 {
        name: name.to_string(),
        boost_only: false,
        omit_on_single_cell: false,
        opacity: expr_one(),
        transform: TransformV2::default(),
        body,
    };

    let mut head_ramp = layer(
        "Head glow",
        LayerBodyV2::HeadRamp {
            color: doc.head.gradient.color.clone(),
            length_cells: doc.head.gradient.length_cells,
        },
    );
    head_ramp.omit_on_single_cell = true;
    head_ramp.opacity = ramp_opacity;

    let mut head_cap = layer(
        "Head cap",
        LayerBodyV2::HeadDisc {
            paint: DiscPaintV2::Ref(fill_ref()),
            radius_ratio: PropExpr::constant(0.5),
        },
    );
    head_cap.omit_on_single_cell = true;

    let mut head_highlight = layer(
        "Head highlight",
        LayerBodyV2::HeadDisc {
            paint: DiscPaintV2::Named(DiscPaintName::RampPeak),
            radius_ratio: PropExpr::constant(0.5),
        },
    );
    head_highlight.omit_on_single_cell = true;

    SkinDocV2 {
        schema_version: SCHEMA_VERSION_V2,
        id: doc.id.clone(),
        name: doc.name.clone(),
        palette: doc.palette.clone(),
        labels: doc.labels.clone(),
        base: doc.base.clone(),
        celebration: doc.celebration.clone(),
        literals: BTreeMap::new(),
        textures: Vec::new(),
        period_ms: doc
            .animation
            .as_ref()
            .map_or(default_period_ms(), |spec| spec.period_ms),
        head_core: HeadCoreV2 {
            ratio: doc.head.core_ratio,
            color: doc.head.core_color.clone(),
        },
        layers: vec![
            layer(
                "Outline",
                LayerBodyV2::Ribbon {
                    region: RegionV2::Contour,
                    color: ColorRef {
                        target: ColorTarget::Slot {
                            slot: SlotName::Outline,
                        },
                        lighten: track_sum(crate::TrackTarget::OutlineLightness).map(PropExpr),
                    },
                    extra_px: doc.outline.extra_px,
                    joints: true,
                    tail_cap: false,
                },
            ),
            layer(
                "Body",
                LayerBodyV2::Ribbon {
                    region: RegionV2::Body,
                    color: fill_ref(),
                    extra_px: 0.0,
                    joints: true,
                    tail_cap: true,
                },
            ),
            head_ramp,
            head_cap,
            head_highlight,
        ],
    }
}

/// Where in the renderer a property's expression is evaluated.
///
/// This is the schema's cost model made explicit, and it decides what an
/// expression may read: an input is available exactly where the renderer knows
/// it. Naming the site rather than capping a tier is what lets an error say
/// *why* — "colours are baked once for every snake wearing the skin, so a
/// palette shift cannot read `boost`" — and it is what the Builder shows
/// beside each fx field so cost is visible where it is incurred.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EvalSite {
    /// Baked into the palette ring at registration. One colour string per
    /// step, shared by every snake wearing the skin — so nothing per-snake.
    Palette,
    /// Once per snake, per frame: opacity, transforms, stop geometry, drift.
    Snake,
    /// Once per cell or per emitted tile: the head glow's curve, a band's
    /// alpha. The only site that may read position along the body.
    Cell,
    /// Like [`EvalSite::Snake`], but the value's *range* has to be knowable
    /// before the skin paints, because that range is what keeps a layer inside
    /// the silhouette. Per-snake inputs are unbounded at registration, so they
    /// are refused here.
    Bounded,
}

impl EvalSite {
    /// What an expression evaluated here is allowed to read.
    pub fn allowed_inputs(self) -> &'static [Input] {
        match self {
            EvalSite::Palette | EvalSite::Bounded => &[Input::Time],
            EvalSite::Snake => &[Input::Time, Input::Len, Input::Boost, Input::Seed],
            EvalSite::Cell => &Input::ALL,
        }
    }

    /// Why this site is limited the way it is, in the author's terms.
    fn because(self) -> &'static str {
        match self {
            EvalSite::Palette => {
                "colours are resolved once per animation step and shared by \
                 every snake wearing the skin"
            }
            EvalSite::Snake => {
                "this is worked out once per snake per frame, before the \
                 renderer knows which cell it is painting"
            }
            EvalSite::Cell => "this is worked out for every cell",
            EvalSite::Bounded => {
                "this value's range has to be checkable before the skin paints \
                 — it is what keeps the layer inside the snake"
            }
        }
    }

    /// `noise` is per-texel wherever it appears, so it is only affordable at
    /// the one site that already runs per cell.
    fn allows_noise(self) -> bool {
        self == EvalSite::Cell
    }
}

/// Validate a v2 document's structure: parses, resolves, and stays inside
/// every static bound. The composited *outcome* checks (label contrast, side
/// reading) are the sampler's job — PRD section 7.3, milestone V2.
pub fn validate_v2(doc: &SkinDocV2) -> Result<(), Vec<SkinDocError>> {
    let mut errors = Vec::new();

    if doc.schema_version != SCHEMA_VERSION_V2 {
        errors.push(SkinDocError::new(
            "schema_version",
            format!(
                "this is the v{SCHEMA_VERSION_V2} validator; version {} documents are \
                 checked by their own validator, and unknown versions fall back \
                 to the classic skin rather than being guessed at",
                doc.schema_version
            ),
        ));
    }
    if doc.id.trim().is_empty() {
        errors.push(SkinDocError::new("id", "a skin needs a catalogue id"));
    }
    if doc.name.trim().is_empty() {
        errors.push(SkinDocError::new("name", "a skin needs a display name"));
    }

    if !(MIN_ANIMATION_PERIOD_MS..=MAX_ANIMATION_PERIOD_MS).contains(&doc.period_ms) {
        errors.push(SkinDocError::new(
            "period_ms",
            "must be between 120ms and 60000ms — faster reads as a flicker",
        ));
    }

    // The palette carries the same hue-window duty it carried in v1. What it
    // no longer carries is the analytic label-contrast check: v1 could compute
    // "what sits under the label" from its closed structure, v2 cannot, and
    // the sampler (PRD 7.3) computes it from the composite instead.
    crate::validate_palette_hues(&doc.palette, &mut errors);

    for (name, hex) in &doc.literals {
        if Rgb::parse(hex).is_none() {
            errors.push(SkinDocError::new(
                format!("literals.{name}"),
                format!("`{hex}` is not a 6-digit hex colour like `#3c8dde`"),
            ));
        }
        if name.trim().is_empty() {
            errors.push(SkinDocError::new("literals", "a literal needs a name"));
        }
    }

    if doc.textures.len() > MAX_TEXTURE_REFS {
        errors.push(SkinDocError::new(
            "textures",
            format!("at most {MAX_TEXTURE_REFS} textures per skin"),
        ));
    }
    let mut texture_names = std::collections::BTreeSet::new();
    for (index, texture) in doc.textures.iter().enumerate() {
        if !crate::content::is_content_ref(&texture.content_ref)
            && !is_builtin_texture(&texture.content_ref)
        {
            errors.push(SkinDocError::new(
                format!("textures[{index}].ref"),
                format!(
                    "must be a content reference like `sha256:<64 hex digits>`, \
                     or first-party art the client ships ({})",
                    BUILTIN_TEXTURES
                        .iter()
                        .map(|art| format!("`{BUILTIN_TEXTURE_PREFIX}{}`", art.id))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            ));
        }
        if !texture_names.insert(texture.name.as_str()) {
            errors.push(SkinDocError::new(
                format!("textures[{index}].name"),
                format!("`{}` is declared twice", texture.name),
            ));
        }
    }

    // The head core: the same authority and the same rules as v1.
    if !(MIN_HEAD_CORE_RATIO..=MAX_HEAD_CORE_RATIO).contains(&doc.head_core.ratio) {
        errors.push(SkinDocError::new(
            "head_core.ratio",
            "must be between 0.05 and 0.5 of a cell",
        ));
    }
    match Rgb::parse(&doc.head_core.color) {
        None => errors.push(SkinDocError::new(
            "head_core.color",
            format!(
                "`{}` is not a 6-digit hex colour like `#3c8dde`",
                doc.head_core.color
            ),
        )),
        Some(core) => {
            let ready = Rgb::parse(READY_CHECK_INK).expect("the ready check ink is a literal");
            let ratio = contrast_ratio(core, ready);
            if ratio < MIN_READY_CHECK_CONTRAST {
                errors.push(SkinDocError::new(
                    "head_core.color",
                    format!(
                        "the roster's white ready-check only reaches {ratio:.1}:1 \
                         on this core; keep the core dark enough to read it \
                         ({MIN_READY_CHECK_CONTRAST}:1 minimum)"
                    ),
                ));
            }
        }
    }

    if let Some(ink) = &doc.labels.ink
        && Rgb::parse(ink).is_none()
    {
        errors.push(SkinDocError::new(
            "labels.ink",
            format!("`{ink}` is not a 6-digit hex colour"),
        ));
    }
    if let Some(swatch) = &doc.labels.swatch
        && Rgb::parse(swatch).is_none()
    {
        errors.push(SkinDocError::new(
            "labels.swatch",
            format!("`{swatch}` is not a 6-digit hex colour"),
        ));
    }

    // The stack. Flattened count first, then each layer in place.
    let flattened = count_flattened(&doc.layers);
    if flattened > MAX_LAYERS {
        errors.push(SkinDocError::new(
            "layers",
            format!(
                "{flattened} layers after flattening groups; {MAX_LAYERS} is the \
                 budget the 200-op ceiling can absorb"
            ),
        ));
    }
    if doc.layers.is_empty() {
        errors.push(SkinDocError::new(
            "layers",
            "a skin with no layers paints nothing; start from a template",
        ));
    }

    for (index, layer) in doc.layers.iter().enumerate() {
        validate_layer(doc, layer, &format!("layers[{index}]"), 0, &mut errors);
    }

    // What the skin actually paints, once the stack is known to be sound.
    // Structure can only say a colour is legal; this says the composite is
    // readable, which is the question v1 could answer analytically and v2
    // cannot.
    if errors.is_empty() {
        errors.extend(crate::sampler::check(doc));
    }

    // Cost last, and only when the stack is otherwise sound: a malformed layer
    // would be priced on a reading of it that is not the one that would ship,
    // and "too expensive" is a confusing thing to be told about a skin that is
    // also invalid.
    if errors.is_empty() {
        let predicted = predict_ops(doc);
        if predicted > MAX_OPS_PER_SNAKE {
            errors.push(SkinDocError::new(
                "layers",
                format!(
                    "this skin costs about {predicted} drawing operations per \
                     snake, over the {MAX_OPS_PER_SNAKE} budget. Eight snakes \
                     share a frame, which is why the budget is per snake rather \
                     than per skin. Fewer layers, longer band repeats, or fewer \
                     gradient stops all buy it back."
                ),
            ));
        }
    }

    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors)
    }
}

fn count_flattened(layers: &[LayerV2]) -> usize {
    layers
        .iter()
        .map(|layer| match &layer.body {
            LayerBodyV2::Group { layers } => count_flattened(layers),
            _ => 1,
        })
        .sum()
}

/// Parse one expression-valued property and hold it to its evaluation site.
fn check_expr(field: &str, site: EvalSite, expr: &PropExpr, errors: &mut Vec<SkinDocError>) {
    let before = errors.len();
    let parsed = match expr.parse() {
        Err(error) => {
            errors.push(SkinDocError::new(field, format!("`{}`: {error}", expr.0)));
            return;
        }
        Ok(parsed) => parsed,
    };

    if let Some(offender) = parsed.inputs().first_outside(site.allowed_inputs()) {
        errors.push(SkinDocError::new(
            field,
            format!(
                "reads `{}`, which is not available here: {}. Available: {}",
                offender.name(),
                site.because(),
                site.allowed_inputs()
                    .iter()
                    .map(|input| format!("`{}`", input.name()))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        ));
    }

    // `noise` reads no input but is per-texel by construction, so the input
    // check above cannot see it. Caught by tier instead.
    if parsed.tier() == Tier::PerTexel && !site.allows_noise() {
        errors.push(SkinDocError::new(
            field,
            format!(
                "uses `noise`, which varies faster than anything else in the \
                 language and is only affordable where the renderer already \
                 works per cell: {}",
                site.because()
            ),
        ));
    }

    // Whether the animation survives being baked into the ring.
    //
    // Gated on reading `time` rather than on the tier, because `time` is
    // quantized to the ring at *every* tier — the head glow's per-cell curve
    // reads the same 32-step clock a baked parameter does, and it is the most
    // visible surface on the snake.
    //
    // Skipped when this field already failed, for the reason the cost gate is
    // withheld from an invalid document: one edit should not produce two
    // complaints about itself.
    if errors.len() == before && parsed.inputs().contains(Input::Time) {
        for env in ring_environments(&parsed) {
            let Some(alias) = crate::ring::ring_alias(&parsed, &env) else {
                continue;
            };
            let detail = match alias {
                crate::ring::RingAlias::Blind => {
                    "the ring samples it at exactly the points where it \
                     repeats, so it paints as a constant"
                        .to_string()
                }
                crate::ring::RingAlias::TooFast { growth } => {
                    format!("it moves {growth:.1}x further between frames than the ring records")
                }
            };
            errors.push(SkinDocError::new(
                field,
                format!(
                    "this animates faster than the {ANIMATION_STEPS}-step ring \
                     can show — a skin is baked into {ANIMATION_STEPS} frames \
                     per cycle, so {detail}, and what plays is a different and \
                     slower motion than the one you wrote. Slow the rate down \
                     inside the expression. Raising the cycle length will not \
                     help: it plays the same {ANIMATION_STEPS} frames over a \
                     longer time rather than giving you more of them."
                ),
            ));
            break;
        }
    }
}

/// The environments a time-reading expression is judged in.
///
/// The product runs over only the inputs the expression actually reads, so the
/// overwhelmingly common time-only case is one environment and one sweep.
///
/// Per environment rather than once over their union, because a rate can
/// depend on the rest: `sin(tau * time * len)` is calm on a short snake and
/// strobes on a long one, and an expression that is identically zero at one
/// `s` would otherwise let that dead sample speak for the whole layer.
fn ring_environments(expr: &Expr) -> Vec<crate::expr::Env> {
    let inputs = expr.inputs();
    let axis = |reads: bool, values: &[f64]| -> Vec<f64> {
        if reads { values.to_vec() } else { vec![0.0] }
    };

    let mut environments = Vec::new();
    for s in axis(inputs.contains(Input::S), &[0.0, 2.0, 12.0]) {
        for t in axis(inputs.contains(Input::T), &[0.0, 0.4]) {
            // The reference body the cost model prices, and a long one.
            for len in axis(
                inputs.contains(Input::Len),
                &[COST_REFERENCE_CELLS as f64, 64.0],
            ) {
                for boost in axis(inputs.contains(Input::Boost), &[0.0, 1.0]) {
                    // Whole numbers: the arena passes a snake's index in the
                    // state, not a fraction, so fractional probes would all
                    // land inside one cell of the noise lattice and test one
                    // field rather than several.
                    for seed in axis(inputs.contains(Input::Seed), &[0.0, 1.0, 7.0]) {
                        environments.push(crate::expr::Env {
                            s,
                            t,
                            len,
                            time: 0.0,
                            boost,
                            seed,
                        });
                    }
                }
            }
        }
    }
    environments
}

fn check_color_ref(doc: &SkinDocV2, field: &str, color: &ColorRef, errors: &mut Vec<SkinDocError>) {
    if let ColorTarget::Literal { literal } = &color.target
        && !doc.literals.contains_key(literal)
    {
        errors.push(SkinDocError::new(
            field,
            format!("names literal `{literal}`, which the document does not declare"),
        ));
    }
    if let Some(lighten) = &color.lighten {
        check_expr(
            &format!("{field}.lighten"),
            EvalSite::Palette,
            lighten,
            errors,
        );
    }
}

fn validate_layer(
    doc: &SkinDocV2,
    layer: &LayerV2,
    field: &str,
    depth: usize,
    errors: &mut Vec<SkinDocError>,
) {
    if layer.name.trim().is_empty() {
        errors.push(SkinDocError::new(
            format!("{field}.name"),
            "a layer needs a name; it is how the panel refers to it",
        ));
    }

    // The head glow is the one layer whose opacity is evaluated per cell,
    // because it is the one layer that already walks them.
    let opacity_site = match &layer.body {
        LayerBodyV2::HeadRamp { .. } => EvalSite::Cell,
        _ => EvalSite::Snake,
    };
    check_expr(
        &format!("{field}.opacity"),
        opacity_site,
        &layer.opacity,
        errors,
    );
    for (name, expr) in layer.transform.fields() {
        check_expr(
            &format!("{field}.transform.{name}"),
            EvalSite::Snake,
            expr,
            errors,
        );
    }

    match &layer.body {
        LayerBodyV2::Group { layers } => {
            // A group is flattened before the compositor ever sees it, and
            // opacity flattens exactly: two opacities multiply into one.
            // A transform does not. Composing two translate/rotate/scale
            // triples is only an affine in general — a rotation between two
            // non-uniform scales is a shear, which this triple cannot express
            // — so a group transform would have to be either a matrix the
            // renderer does not have or an approximation that looks right in
            // the panel and wrong on a corner. Refused rather than rounded.
            if !layer.transform.is_identity() {
                errors.push(SkinDocError::new(
                    format!("{field}.transform"),
                    "a group cannot carry a transform: groups are flattened \
                     away before painting, and two transforms do not combine \
                     into one without shearing. Put the transform on each \
                     layer inside the group.",
                ));
            }
            if depth >= MAX_GROUP_DEPTH {
                errors.push(SkinDocError::new(
                    field.to_string(),
                    "a group inside a group; one level is the limit, for the \
                     panel's legibility as much as the compiler's",
                ));
                return;
            }
            if layers.is_empty() {
                errors.push(SkinDocError::new(
                    format!("{field}.layers"),
                    "an empty group should just be removed",
                ));
            }
            for (index, child) in layers.iter().enumerate() {
                validate_layer(
                    doc,
                    child,
                    &format!("{field}.layers[{index}]"),
                    depth + 1,
                    errors,
                );
            }
        }
        LayerBodyV2::Ribbon {
            region,
            color,
            extra_px,
            ..
        } => {
            check_color_ref(doc, &format!("{field}.color"), color, errors);
            match region {
                RegionV2::Contour => {
                    if !(MIN_OUTLINE_EXTRA_PX..=MAX_OUTLINE_EXTRA_PX).contains(extra_px) {
                        errors.push(SkinDocError::new(
                            format!("{field}.extra_px"),
                            format!(
                                "must be between {MIN_OUTLINE_EXTRA_PX} and \
                                 {MAX_OUTLINE_EXTRA_PX}; the contour is the only \
                                 source of overhang and the roster row is sized \
                                 for it"
                            ),
                        ));
                    }
                }
                _ => {
                    if *extra_px != 0.0 {
                        errors.push(SkinDocError::new(
                            format!("{field}.extra_px"),
                            "only a contour ribbon may paint beyond the body",
                        ));
                    }
                }
            }
        }
        LayerBodyV2::Span {
            region,
            span,
            source,
            ..
        } => {
            if *region == RegionV2::Contour {
                errors.push(SkinDocError::new(
                    format!("{field}.region"),
                    "spans paint inside the body; the contour belongs to \
                     ribbons and the Boost band",
                ));
            }
            if span.min < 0.0 || !span.min.is_finite() {
                errors.push(SkinDocError::new(
                    format!("{field}.span.min"),
                    "must be a non-negative length in cells",
                ));
            }
            if let Some(natural) = span.natural
                && (natural <= 0.0 || !natural.is_finite())
            {
                errors.push(SkinDocError::new(
                    format!("{field}.span.natural"),
                    "must be a positive length in cells, or omitted for \
                     `whatever is left`",
                ));
            }
            validate_source(doc, field, source, errors);
        }
        LayerBodyV2::HeadDisc {
            paint,
            radius_ratio,
        } => {
            if let DiscPaintV2::Ref(color) = paint {
                check_color_ref(doc, &format!("{field}.paint"), color, errors);
            }
            // Bounded: the disc may not escape the silhouette, and that has
            // to be provable at registration.
            check_expr(
                &format!("{field}.radius_ratio"),
                EvalSite::Bounded,
                radius_ratio,
                errors,
            );
        }
        LayerBodyV2::HeadRamp {
            color,
            length_cells,
        } => {
            if Rgb::parse(color).is_none() {
                errors.push(SkinDocError::new(
                    format!("{field}.color"),
                    format!("`{color}` is not a 6-digit hex colour"),
                ));
            }
            if !(0.0..=64.0).contains(length_cells) {
                errors.push(SkinDocError::new(
                    format!("{field}.length_cells"),
                    "must be between 0 and 64 cells",
                ));
            }
        }
    }
}

fn validate_source(
    doc: &SkinDocV2,
    field: &str,
    source: &SourceV2,
    errors: &mut Vec<SkinDocError>,
) {
    match source {
        SourceV2::Solid { color } => {
            check_color_ref(doc, &format!("{field}.source.color"), color, errors);
        }
        SourceV2::Gradient { stops, .. } => {
            if !(MIN_GRADIENT_STOPS..=MAX_GRADIENT_STOPS).contains(&stops.len()) {
                errors.push(SkinDocError::new(
                    format!("{field}.source.stops"),
                    format!(
                        "a gradient needs {MIN_GRADIENT_STOPS} to \
                         {MAX_GRADIENT_STOPS} stops; each is a canvas call per \
                         run per frame"
                    ),
                ));
            }
            for (index, stop) in stops.iter().enumerate() {
                let stop_field = format!("{field}.source.stops[{index}]");
                check_expr(
                    &format!("{stop_field}.offset"),
                    EvalSite::Snake,
                    &stop.offset,
                    errors,
                );
                check_expr(
                    &format!("{stop_field}.alpha"),
                    EvalSite::Snake,
                    &stop.alpha,
                    errors,
                );
                check_color_ref(doc, &format!("{stop_field}.color"), &stop.color, errors);
            }
        }
        SourceV2::Band {
            color,
            period_cells,
            duty,
            phase_cells,
            half_width,
            t_center,
            alpha,
        } => {
            check_color_ref(doc, &format!("{field}.source.color"), color, errors);
            if !(period_cells.is_finite() && *period_cells > 0.0) {
                errors.push(SkinDocError::new(
                    format!("{field}.source.period_cells"),
                    "must be a positive length in cells; the repeat geometry \
                     decides the op count, which is why it cannot animate",
                ));
            }
            if !(0.0..=1.0).contains(duty) {
                errors.push(SkinDocError::new(
                    format!("{field}.source.duty"),
                    "must be between 0 and 1 of each period",
                ));
            }
            if !phase_cells.is_finite() {
                errors.push(SkinDocError::new(
                    format!("{field}.source.phase_cells"),
                    "must be a length in cells",
                ));
            }
            // Bounded: |t_center| + half_width is what keeps a body layer off
            // the Boost band.
            check_expr(
                &format!("{field}.source.half_width"),
                EvalSite::Bounded,
                half_width,
                errors,
            );
            check_expr(
                &format!("{field}.source.t_center"),
                EvalSite::Bounded,
                t_center,
                errors,
            );
            if let Some(alpha) = alpha {
                check_expr(
                    &format!("{field}.source.alpha"),
                    EvalSite::Cell,
                    alpha,
                    errors,
                );
            }
        }
        SourceV2::Image {
            texture,
            fit,
            fade,
            drift_cells,
        } => {
            if !doc.textures.iter().any(|entry| &entry.name == texture) {
                errors.push(SkinDocError::new(
                    format!("{field}.source.texture"),
                    format!(
                        "names texture `{texture}`, which the document does not \
                         declare"
                    ),
                ));
            }
            if let FitV2::Tile {
                cells_per_repeat: Some(cells),
            } = fit
                && !(cells.is_finite() && *cells > 0.0)
            {
                errors.push(SkinDocError::new(
                    format!("{field}.source.fit.cells_per_repeat"),
                    "must be a positive length in cells",
                ));
            }
            if let FitV2::Cutout { cells_tall } = fit
                && !(cells_tall.is_finite() && *cells_tall > 0.0)
            {
                errors.push(SkinDocError::new(
                    format!("{field}.source.fit.cells_tall"),
                    "must be a positive height in cells",
                ));
            }
            if let Some(fade) = fade {
                let sane = fade.lead_cells.is_finite()
                    && fade.lead_cells >= 0.0
                    && fade.trail_cells.is_finite()
                    && fade.trail_cells >= 0.0;
                if !sane {
                    errors.push(SkinDocError::new(
                        format!("{field}.source.fade"),
                        "fade lengths must be non-negative cells",
                    ));
                }
                let fades = fade.lead_cells > 0.0 || fade.trail_cells > 0.0;
                if fades && !(1..=64).contains(&fade.steps) {
                    errors.push(SkinDocError::new(
                        format!("{field}.source.fade.steps"),
                        "must be 1 to 64 slices; each is a blit per run",
                    ));
                }
            }
            check_expr(
                &format!("{field}.source.drift_cells"),
                EvalSite::Snake,
                drift_cells,
                errors,
            );
        }
        SourceV2::Text {
            content,
            color,
            scale,
        } => {
            check_color_ref(doc, &format!("{field}.source.color"), color, errors);
            if content.is_empty() || content.len() > MAX_TEXT_CONTENT_LEN {
                errors.push(SkinDocError::new(
                    format!("{field}.source.content"),
                    format!("must be 1 to {MAX_TEXT_CONTENT_LEN} characters"),
                ));
            }
            if let Some(bad) = content.chars().find(|c| !TEXT_CHARSET.contains(*c)) {
                errors.push(SkinDocError::new(
                    format!("{field}.source.content"),
                    format!("`{bad}` is not in the glyph set; available: {TEXT_CHARSET}"),
                ));
            }
            if !(0.1..=1.0).contains(scale) {
                errors.push(SkinDocError::new(
                    format!("{field}.source.scale"),
                    "must be between 0.1 and 1 of a cell",
                ));
            }
        }
    }
}

/// The snake a document's cost is quoted against.
///
/// Deliberately the same body `client::skin::perf` measures its census on — a
/// straight 21-cell snake at the arena's largest cell, boosting — so the
/// Builder's meter and the shipped budget are talking about the same snake
/// rather than two plausible ones.
pub const COST_REFERENCE_CELLS: usize = 21;
pub const COST_REFERENCE_RUNS: usize = 1;

/// A predicted upper bound on the canvas ops one snake costs.
///
/// **An upper bound, not an estimate.** A budget that sometimes under-predicts
/// is worse than none: it would clear a skin at save time and blow the frame
/// in a match, where nobody could attribute it. Every term below is the most
/// the corresponding lowering can emit, so `predicted >= recorded` always — a
/// property the client pins by recording real skins and comparing.
///
/// It is deliberately in this crate rather than beside the renderer, because
/// the Builder's live meter, the save-time gate and CI all have to reach the
/// same verdict, and only this crate is compiled into all three.
pub fn predict_ops(doc: &SkinDocV2) -> usize {
    let runs = COST_REFERENCE_RUNS;
    let cells = COST_REFERENCE_CELLS;

    // The two system layers: the Boost band (a contour ribbon, present because
    // the reference snake is boosting) and the head core (a disc).
    let mut total = ribbon_ops(runs, true, false) + DISC_OPS;

    for layer in &doc.layers {
        total += layer_ops(layer, runs, cells);
    }
    total
}

const DISC_OPS: usize = 5;

fn layer_ops(layer: &LayerV2, runs: usize, cells: usize) -> usize {
    // Opacity that is not the constant 1 emits a set and a reset; a non-identity
    // transform emits a save, up to three ops, and a restore.
    let constant_one = layer
        .opacity
        .parse()
        .map(|expr| expr.inputs().is_empty() && expr.eval(&crate::expr::Env::default()) == 1.0)
        .unwrap_or(false);
    let mut total = usize::from(!constant_one) * 2;
    if !layer.transform.is_identity() {
        total += 5;
    }

    total
        + match &layer.body {
            LayerBodyV2::Group { layers } => layers
                .iter()
                .map(|child| layer_ops(child, runs, cells))
                .sum(),
            LayerBodyV2::Ribbon {
                joints, tail_cap, ..
            } => ribbon_ops(runs, *joints, *tail_cap),
            LayerBodyV2::HeadRamp { length_cells, .. } => {
                // One set_fill and one fill_rect per covered cell.
                2 * (length_cells.max(0.0).ceil() as usize).min(cells)
            }
            LayerBodyV2::HeadDisc { .. } => DISC_OPS,
            LayerBodyV2::Span { source, .. } => {
                // A span opens and closes one clip.
                let clip = 4 + runs * 3;
                clip + source_ops(source, runs, cells)
            }
        }
}

fn ribbon_ops(runs: usize, joints: bool, tail_cap: bool) -> usize {
    // Colour and width, a stroke and a fill per run, a disc at each joint, and
    // a capped tail.
    4 + runs * 3 + usize::from(joints) * runs + usize::from(tail_cap) * 4
}

fn source_ops(source: &SourceV2, runs: usize, cells: usize) -> usize {
    let per_run_frame = 3; // save, transform, restore
    match source {
        SourceV2::Solid { .. } => 1 + runs,
        SourceV2::Gradient { stops, .. } => runs * (per_run_frame + 2 + stops.len()),
        SourceV2::Band {
            period_cells,
            alpha,
            ..
        } => {
            // One more repeat than the body strictly holds: a repeat may
            // straddle either end.
            let repeats = (cells as f64 / period_cells.max(0.5)).ceil() as usize + 1;
            1 + repeats * (runs + usize::from(alpha.is_some()) * 2)
        }
        SourceV2::Image { fit, fade, .. } => {
            let repeats = match fit {
                FitV2::Tile { cells_per_repeat } => {
                    (cells as f64 / cells_per_repeat.unwrap_or(1.0).max(0.25)).ceil() as usize + 1
                }
                _ => 1,
            };
            let slices = fade.map_or(1, |fade| {
                if fade.lead_cells > 0.0 || fade.trail_cells > 0.0 {
                    fade.steps.max(1) * 2
                } else {
                    1
                }
            });
            runs * (per_run_frame + repeats * slices)
        }
        // One blit per covered cell, plus its alpha.
        SourceV2::Text { .. } => runs * per_run_frame + cells * 2,
    }
}

/// A starting point for a new skin.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Template {
    pub id: String,
    pub label: String,
    pub document: SkinDocV2,
    /// The fixture role name the picker should paint this card in.
    ///
    /// A card exists to show what the template *is*, and for a template built
    /// around one palette slot that means painting that slot. It is not
    /// cosmetic: friendly colours are pinned to a cool hue window, so a yellow
    /// board is only legal — and only truthful — in a free-for-all slot.
    pub preview_role: String,
}

/// The documents a new skin can start from.
///
/// Ordinary v2 documents rather than code, which is the point: a template is
/// something an author could have built in the panel, and taking one apart is
/// how the panel teaches itself.
///
/// None of them is classic. Classic's document carries a recorded exemption
/// from the label rule — see `LIT_LABEL_EXEMPT` — so starting a new skin from
/// it would open the editor on a document the validator immediately refuses,
/// which is a poor first impression and a baffling one.
pub fn templates() -> Vec<Template> {
    let pair = |fill: &str, outline: &str| ColorPair {
        fill: fill.to_string(),
        outline: outline.to_string(),
        accent: None,
    };
    let base = |name: &str| SkinDocV2 {
        schema_version: SCHEMA_VERSION_V2,
        id: "draft@1".to_string(),
        name: name.to_string(),
        // The colours a player already knows, taken from the shipped classic
        // document rather than invented near it. A template is the snake you
        // had a moment ago with something added, and a starting point that
        // silently restyles the body is a worse starting point — the author
        // cannot tell which difference is the template and which is theirs.
        palette: RolePalette {
            friendly: [pair("#70bfe3", "#5299bb"), pair("#3c8dde", "#286eae")],
            enemy: [pair("#ff6b6b", "#b84444"), pair("#e34e5b", "#a92f3a")],
            free_for_all: [
                pair("#70bfe3", "#5299bb"),
                pair("#ff6b6b", "#b84444"),
                // Classic's steel is #556270, and this is the one colour a
                // template may not copy: it is the weak spot classic carries a
                // recorded exemption for, where the head glow lightens the body
                // to a mid-grey the derived white label only reaches 3.0:1 on.
                // Lightening past the threshold flips the derived label dark,
                // which is what actually fixes it — darkening keeps the white
                // label and the glow washes it out again.
                pair("#93a3b5", "#5d6e81"),
                pair("#f7b731", "#a87d1f"),
            ],
        },
        labels: LabelStyle::default(),
        base: None,
        celebration: None,
        literals: BTreeMap::new(),
        textures: Vec::new(),
        period_ms: 2_400.0,
        head_core: HeadCoreV2 {
            ratio: 0.38,
            color: "#333333".to_string(),
        },
        layers: Vec::new(),
    };

    let layer = |name: &str, opacity: &str, body: LayerBodyV2| LayerV2 {
        name: name.to_string(),
        boost_only: false,
        omit_on_single_cell: false,
        opacity: PropExpr(opacity.to_string()),
        transform: TransformV2::default(),
        body,
    };
    let ribbon = |name: &str, region: RegionV2, slot: SlotName, extra_px: f64, tail_cap: bool| {
        layer(
            name,
            "1",
            LayerBodyV2::Ribbon {
                region,
                color: ColorRef::slot(slot),
                extra_px,
                joints: true,
                tail_cap,
            },
        )
    };
    let glow = |length: f64, peak: f64| {
        let mut glow = layer(
            "Head glow",
            &format!("(1 - s / {length}) * {peak}"),
            LayerBodyV2::HeadRamp {
                color: "#ffffff".to_string(),
                length_cells: length,
            },
        );
        glow.omit_on_single_cell = true;
        glow
    };

    let stop = |offset: &str, target: ColorTarget, alpha: &str| StopV2 {
        offset: PropExpr(offset.to_string()),
        color: ColorRef {
            target,
            lighten: None,
        },
        alpha: PropExpr(alpha.to_string()),
    };
    // The same stop, but painted in the role's own fill pushed up or down in
    // lightness. A crest with a *literal* colour would have to pick one hue
    // for every role, and a warm crest on a blue friendly snake is two teams'
    // colours on one snake; deriving it from the fill is hue-safe in every
    // role by construction, and it deepens the colour rather than tinting it.
    let lit_stop = |offset: &str, lighten: &str, alpha: &str| StopV2 {
        offset: PropExpr(offset.to_string()),
        color: ColorRef {
            target: ColorTarget::Slot {
                slot: SlotName::Fill,
            },
            lighten: Some(PropExpr(lighten.to_string())),
        },
        alpha: PropExpr(alpha.to_string()),
    };
    // A gleam travelling the body, as three stops whose positions read the
    // clock. `alpha` and the crest's width are what separate a whisper from a
    // sweep; `easing` reshapes *when* it travels rather than how far.
    let shine = |name: &str, width: f64, alpha: &str, easing: &str| {
        layer(
            name,
            "1",
            LayerBodyV2::Span {
                region: RegionV2::Body,
                clip: ClipV2::Silhouette,
                span: SpanV2::whole(),
                corner: CornerV2::Fan,
                source: SourceV2::Gradient {
                    axis: GradientAxis::AlongBody,
                    stops: vec![
                        stop(
                            &format!("{easing} - {width}"),
                            ColorTarget::Slot {
                                slot: SlotName::Fill,
                            },
                            "0",
                        ),
                        stop(
                            easing,
                            ColorTarget::Literal {
                                literal: "gleam".to_string(),
                            },
                            alpha,
                        ),
                        stop(
                            &format!("{easing} + {width}"),
                            ColorTarget::Slot {
                                slot: SlotName::Fill,
                            },
                            "0",
                        ),
                    ],
                },
            },
        )
    };

    // The moving gradient: a shadow and a highlight rolling along the body,
    // one behind the other, both painted in the snake's own colour.
    //
    // It is deliberately out of step with the white Shine above it. That one
    // peaks at the half-turn; this one is offset a quarter, so the two crests
    // cross twice a cycle instead of travelling as one thick band — the
    // interference is what stops it reading as simply a second highlight.
    let sheen = |name: &str| {
        let travel = "tri(time + 0.25)";
        layer(
            name,
            "1",
            LayerBodyV2::Span {
                region: RegionV2::Body,
                clip: ClipV2::Silhouette,
                span: SpanV2::whole(),
                corner: CornerV2::Fan,
                source: SourceV2::Gradient {
                    axis: GradientAxis::AlongBody,
                    stops: vec![
                        lit_stop(&format!("{travel} - 0.44"), "-0.34", "0"),
                        // The shadow is a hair stronger than the highlight,
                        // and that is load-bearing rather than taste: the
                        // sampler judges a gradient by its single strongest
                        // stop, and `max_by` keeps the last of equals. Equal
                        // alphas would quietly move the model onto the
                        // lightening — the one direction that cannot fail a
                        // contrast floor — and the check would go slack
                        // without anything failing to say so.
                        lit_stop(&format!("{travel} - 0.22"), "-0.34", "0.42"),
                        // The wave passes through the body's own colour on its
                        // way from shadow to highlight, so there is no seam.
                        stop(
                            travel,
                            ColorTarget::Slot {
                                slot: SlotName::Fill,
                            },
                            "0",
                        ),
                        lit_stop(&format!("{travel} + 0.22"), "0.45", "0.4"),
                        lit_stop(&format!("{travel} + 0.44"), "0.45", "0"),
                    ],
                },
            },
        )
    };

    // A board is two lanes of squares half a period out of phase — which is
    // exactly two band layers, and is how the shipped checkerboards are built.
    //
    // `lighten` is Harlequin's contribution, and Harlequin turns out not to
    // have a gradient in it at all: its two lanes trade emphasis in exact
    // antiphase, one cycle per turn, so the board's two colours continuously
    // swap dominance. That see-saw under a travelling highlight is what reads
    // as the colours never sitting still.
    let lane = |name: &str, t_center: f64, phase: f64, period: f64, lighten: &str| {
        let mut lane = layer(
            name,
            "1",
            LayerBodyV2::Span {
                region: RegionV2::Body,
                clip: ClipV2::Silhouette,
                span: SpanV2::whole(),
                corner: CornerV2::Fan,
                source: SourceV2::Band {
                    color: ColorRef {
                        target: ColorTarget::Slot {
                            slot: SlotName::Accent,
                        },
                        lighten: Some(PropExpr(lighten.to_string())),
                    },
                    period_cells: period,
                    duty: 0.5,
                    phase_cells: phase * period,
                    half_width: PropExpr("0.25".to_string()),
                    t_center: PropExpr(format!("{t_center}")),
                    alpha: None,
                },
            },
        );
        // Half a cell of board on a one-cell snake reads as a smudge, and the
        // head cap covers most of it anyway.
        lane.omit_on_single_cell = true;
        lane
    };

    let mut classic = base("My skin");
    classic
        .literals
        .insert("gleam".to_string(), "#ffffff".to_string());
    classic.layers = vec![
        ribbon("Outline", RegionV2::Contour, SlotName::Outline, 2.0, false),
        ribbon("Body", RegionV2::Body, SlotName::Fill, 0.0, true),
        // Faint and unhurried: the default snake, lit, with just enough
        // movement that the preview is obviously alive.
        shine("Shine", 0.12, "0.1", "saw(time)"),
        glow(10.0, 0.3),
    ];

    let mut pattern = base("Pattern");
    pattern
        .literals
        .insert("gleam".to_string(), "#ffffff".to_string());
    // A board with Pitlane's two-cell squares, checked in Harlequin's manner:
    // the second square is its own colour on the same side of the wheel as the
    // first, never a colour borrowed from the other team. The check is the
    // accent rather than a literal, so it flips with the side — a board reads
    // as a board in every role or it is not a skin, it is one snake's costume.
    //
    // Which is why the yellow board lives in `free_for_all[3]` and the card
    // paints that slot: friendly is pinned to a cool hue window, so a yellow
    // friendly snake is not a choice the sampler would allow, and a yellow
    // check over a blue body is two teams' colours on one snake.
    let check = |slot: &mut ColorPair, hex: &str| slot.accent = Some(hex.to_string());
    check(&mut pattern.palette.friendly[0], "#c8ecfa");
    check(&mut pattern.palette.friendly[1], "#a8cdf2");
    check(&mut pattern.palette.enemy[0], "#fbcd82");
    check(&mut pattern.palette.enemy[1], "#f2b75f");
    check(&mut pattern.palette.free_for_all[0], "#c8ecfa");
    check(&mut pattern.palette.free_for_all[1], "#fbcd82");
    check(&mut pattern.palette.free_for_all[2], "#93a3b5");
    // The two yellows: the game's own snake yellow, checked with a pale gold.
    check(&mut pattern.palette.free_for_all[3], "#ffe08a");
    pattern.period_ms = 1_400.0;
    // Harlequin trades its lanes' *opacity*; this board trades their
    // lightness, and that is a measurement rather than a preference. Veiling a
    // check toward the body works when the two are far apart — Harlequin's
    // cyan on violet is 0.2364 in OKLab — but this board is two yellows only
    // 0.1085 apart, and the same trade moves them 0.0437, under the 0.08 that
    // `color.rs` calls a difference nobody would miss. The antiphase pair
    // below moves them 0.1407 instead. Doing both is worse than either: the
    // swings partly cancel, and the dimmed diagonal sinks into the body.
    //
    // `sin` rather than Harlequin's `cos` also fixes a wart in the original.
    // With `cos`, step 0 is the *extreme* of the swing, so the roster card,
    // every golden and every reduced-motion viewer hold a fully tilted board.
    // With `sin` step 0 is zero shift on both lanes, and the resting pose is
    // the two-tone board as authored.
    let tilt = "0.18 * sin(tau * time)";
    let tilt_opposed = "0.18 * sin(tau * (time + 0.5))";
    pattern.layers = vec![
        ribbon("Outline", RegionV2::Contour, SlotName::Outline, 2.0, false),
        ribbon("Body", RegionV2::Body, SlotName::Fill, 0.0, true),
        lane("Board, upper", -0.25, 0.0, 2.0, tilt),
        lane("Board, lower", 0.25, 0.5, 2.0, tilt_opposed),
        sheen("Sheen"),
        // Stronger, faster, and eased: `tri` in place of `saw` makes the crest
        // sweep down the body and back rather than snapping to the head, and
        // squaring it holds it at the ends and hurries it through the middle.
        shine("Shine", 0.16, "0.34", "tri(time) * tri(time)"),
        glow(10.0, 0.3),
    ];

    let mut sprite = base("Sprite");
    sprite.textures.push(TextureRefV2 {
        name: "flag".to_string(),
        content_ref: format!("{BUILTIN_TEXTURE_PREFIX}stars-and-stripes.v1"),
        kind: TextureKindV2::Sheet,
    });
    let mut flag = layer(
        "Flag",
        "1",
        LayerBodyV2::Span {
            region: RegionV2::Body,
            clip: ClipV2::Silhouette,
            // Pinned to the head and allowed to end. A flag is a thing with a
            // top and a bottom; repeating it would stamp a row of little flags,
            // which is not what a flag looks like.
            span: SpanV2 {
                from: AnchorV2::Head,
                natural: Some(20.0),
                min: 3.0,
                priority: 10,
            },
            corner: CornerV2::Fan,
            source: SourceV2::Image {
                texture: "flag".to_string(),
                fit: FitV2::Clip,
                // The fade is what makes ending look intentional rather than
                // cut off — without it the twentieth cell is a hard vertical
                // line with the base colour after it.
                fade: Some(FadeV2 {
                    lead_cells: 0.0,
                    trail_cells: 6.0,
                    steps: 12,
                }),
                drift_cells: PropExpr("0".to_string()),
            },
        },
    );
    flag.omit_on_single_cell = true;
    sprite.layers = vec![
        ribbon("Outline", RegionV2::Contour, SlotName::Outline, 2.0, false),
        ribbon("Body", RegionV2::Body, SlotName::Fill, 0.0, true),
        flag,
        glow(10.0, 0.3),
    ];

    vec![
        Template {
            id: "classic".to_string(),
            label: "Classic".to_string(),
            document: classic,
            preview_role: "own".to_string(),
        },
        Template {
            id: "pattern".to_string(),
            label: "Pattern".to_string(),
            document: pattern,
            preview_role: "ffa3".to_string(),
        },
        Template {
            id: "sprite".to_string(),
            label: "Sprite".to_string(),
            document: sprite,
            preview_role: "own".to_string(),
        },
    ]
}

/// A document of either version, told apart by `schema_version`.
#[derive(Clone, Debug, PartialEq)]
pub enum AnySkinDoc {
    V1(SkinDoc),
    V2(SkinDocV2),
}

/// Parse and validate a document of either schema version.
///
/// Unknown versions are refused with the version named — the caller's
/// fallback (render classic) is the same one it has always had for a
/// document it cannot compile.
pub fn load_any(json: &str) -> Result<AnySkinDoc, Vec<SkinDocError>> {
    #[derive(Deserialize)]
    struct Peek {
        schema_version: u32,
    }
    let peek: Peek = serde_json::from_str(json)
        .map_err(|error| vec![SkinDocError::new("document", error.to_string())])?;

    match peek.schema_version {
        crate::SCHEMA_VERSION => crate::load(json).map(AnySkinDoc::V1),
        SCHEMA_VERSION_V2 => {
            let doc: SkinDocV2 = serde_json::from_str(json)
                .map_err(|error| vec![SkinDocError::new("document", error.to_string())])?;
            validate_v2(&doc)?;
            Ok(AnySkinDoc::V2(doc))
        }
        other => Err(vec![SkinDocError::new(
            "schema_version",
            format!(
                "version {other} is not one this build understands (1 or 2); \
                 falling back to the classic skin instead of guessing"
            ),
        )]),
    }
}

/// Compile-time exhaustiveness: destructure every v2 struct so a field can
/// be added but not forgotten. The descriptor (milestone V3) will consume
/// these the way `describe::exhaustiveness` consumes v1's; until then the
/// destructuring alone forces the author of a new field to visit this file
/// and decide what the Builder shows for it.
#[allow(dead_code)]
mod exhaustiveness {
    use super::*;

    fn document(doc: SkinDocV2) {
        let SkinDocV2 {
            schema_version: _,
            id: _,
            name: _,
            palette: _,
            labels: _,
            base: _,
            celebration: _,
            literals: _,
            textures: _,
            period_ms: _,
            head_core: _,
            layers: _,
        } = doc;
    }

    fn layer(layer: LayerV2) {
        let LayerV2 {
            name: _,
            boost_only: _,
            omit_on_single_cell: _,
            opacity: _,
            transform: _,
            body,
        } = layer;
        match body {
            LayerBodyV2::Group { layers: _ } => {}
            LayerBodyV2::Ribbon {
                region: _,
                color: _,
                extra_px: _,
                joints: _,
                tail_cap: _,
            } => {}
            LayerBodyV2::Span {
                region: _,
                clip: _,
                span: _,
                corner: _,
                source: _,
            } => {}
            LayerBodyV2::HeadDisc {
                paint: _,
                radius_ratio: _,
            } => {}
            LayerBodyV2::HeadRamp {
                color: _,
                length_cells: _,
            } => {}
        }
    }

    fn source(source: SourceV2) {
        match source {
            SourceV2::Solid { color: _ } => {}
            SourceV2::Gradient { axis: _, stops: _ } => {}
            SourceV2::Band {
                color: _,
                period_cells: _,
                duty: _,
                phase_cells: _,
                half_width: _,
                t_center: _,
                alpha: _,
            } => {}
            SourceV2::Image {
                texture: _,
                fit: _,
                fade: _,
                drift_cells: _,
            } => {}
            SourceV2::Text {
                content: _,
                color: _,
                scale: _,
            } => {}
        }
    }

    fn small_parts(
        transform: TransformV2,
        span: SpanV2,
        stop: StopV2,
        fade: FadeV2,
        core: HeadCoreV2,
        texture: TextureRefV2,
        color: ColorRef,
    ) {
        let TransformV2 {
            translate_s: _,
            translate_t: _,
            scale_s: _,
            scale_t: _,
            rotate_turns: _,
        } = transform;
        let SpanV2 {
            from: _,
            natural: _,
            min: _,
            priority: _,
        } = span;
        let StopV2 {
            offset: _,
            color: _,
            alpha: _,
        } = stop;
        let FadeV2 {
            lead_cells: _,
            trail_cells: _,
            steps: _,
        } = fade;
        let HeadCoreV2 { ratio: _, color: _ } = core;
        let TextureRefV2 {
            name: _,
            content_ref: _,
            kind: _,
        } = texture;
        let ColorRef {
            target: _,
            lighten: _,
        } = color;
    }
}

