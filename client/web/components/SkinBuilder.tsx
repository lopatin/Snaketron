/**
 * The Skin Builder: a layers panel and a preview.
 *
 * Photoshop's left-hand side without its canvas tools — a stack you reorder and
 * an inspector for whatever is selected. The preview is output, never input.
 *
 * There is no Animations section, and its absence is the point rather than an
 * omission. Animation is not a feature a skin has; it is what happens when a
 * property's expression reads `time`. So every animatable field is a number
 * with an **fx** toggle, because a constant *is* a constant expression — the
 * two states are one value seen two ways.
 *
 * Every control is generated by walking the descriptor the Rust crate emits.
 * That crate destructures the whole v2 vocabulary in an exhaustiveness module,
 * so a variant added without a control breaks its build; the `never` assignment
 * at the end of {@link Control} is the same guarantee on this side. Between
 * them, the panel cannot drift from the object model the renderer runs.
 */

interface SkinBuilderProps {
  onOpenAuth: () => void;
  onOpenAccount: (view: AccountModalView) => void;
}

/** Mirrors `skin_schema::describe_v2::KindV2`. */
type KindV2 =
  | { control: 'color' }
  | { control: 'colorRef'; slots: Choice[] }
  | { control: 'text'; maxLength: number; charset?: string }
  | { control: 'toggle' }
  | { control: 'number'; min: number; max: number; step: number }
  | {
      control: 'expression';
      min: number;
      max: number;
      step: number;
      inputs: string[];
      site: string;
      siteLabel: string;
    }
  | { control: 'choice'; options: Choice[] }
  | { control: 'group'; children: FieldV2[] }
  | { control: 'optional'; children: FieldV2[] }
  | {
      control: 'list';
      itemLabel: string;
      itemDefault: unknown;
      minItems: number;
      maxItems: number;
      children: FieldV2[];
    }
  | { control: 'variant'; tag: string; options: Variant[] };

interface Choice {
  value: string;
  label: string;
  help?: string;
}

interface Variant {
  value: string;
  label: string;
  help?: string;
  default: Record<string, unknown>;
  children: FieldV2[];
}

interface FieldV2 {
  path: string;
  label: string;
  kind: KindV2;
  help?: string;
  default?: unknown;
}

interface SchemaV2 {
  document: FieldV2[];
  layer: FieldV2[];
  addLayer: Variant[];
  systemLayers: { name: string; position: string; help: string }[];
  limits: { maxLayers: number; maxOps: number; maxTextures: number };
}

